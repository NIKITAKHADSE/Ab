CREATE DATABASE IF NOT EXISTS abssolute_homtel CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE abssolute_homtel;
CREATE TABLE booking_enquiries (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, reference_code VARCHAR(32) NOT NULL UNIQUE, stay_type VARCHAR(30) NOT NULL,
 check_in DATE NOT NULL, check_out DATE NOT NULL, guests TINYINT UNSIGNED NOT NULL, name VARCHAR(100) NOT NULL,
 email VARCHAR(190) NOT NULL, phone VARCHAR(30) NOT NULL, special_requests TEXT, ip_hash CHAR(64), status VARCHAR(30) NOT NULL DEFAULT 'new', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX(created_at), INDEX(email)
) ENGINE=InnoDB;
CREATE TABLE contact_enquiries (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(190) NOT NULL, phone VARCHAR(30),
 message TEXT NOT NULL, ip_hash CHAR(64), status VARCHAR(30) NOT NULL DEFAULT 'new', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX(created_at), INDEX(email)
) ENGINE=InnoDB;

